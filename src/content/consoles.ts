import type { CodexEntry } from './codex';

interface ConsoleExtras {
  handheld?: boolean;
  related?: string[];
}

// Generation pages list these automatically, so a console only needs adding here.
const machine = (
  id: string,
  generation: number,
  year: number,
  title: string,
  maker: string,
  sales: string,
  summary: string,
  paragraphs: string[],
  { handheld, related }: ConsoleExtras = {},
): CodexEntry => {
  const entry: CodexEntry = {
    id: `console-${id}`,
    category: 'consoles',
    title,
    summary,
    console: { generation, year, maker, sales },
    sections: paragraphs.map((text) => ({ text })),
  };
  if (handheld && entry.console) entry.console.handheld = true;
  if (related) entry.related = related;
  return entry;
};

